"""把 ops[] 编译成一段 Lua 程序（spec §6.2）。"""

import json
import re
from pathlib import Path

from pydantic import BaseModel

from src.v2.registry import OpSpec

RESULT_MARKER = "__MCP_JSON__"

_LUA_IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")

_LUA_KEYWORDS = frozenset({
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function",
    "goto", "if", "in", "local", "nil", "not", "or", "repeat", "return",
    "then", "true", "until", "while",
})


def lua_string(s: str) -> str:
    out = ['"']
    for ch in s:
        code = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif code < 32 or code == 127:
            out.append(f"\\x{code:02x}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def lua_value(v) -> str:
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v != v or v in (float("inf"), float("-inf")):
            raise ValueError(f"cannot serialize non-finite number: {v}")
        return repr(v)
    if isinstance(v, str):
        return lua_string(v)
    if isinstance(v, (list, tuple)):
        return "{" + ",".join(lua_value(x) for x in v) + "}"
    if isinstance(v, dict):
        parts = []
        for k, val in v.items():
            if (
                isinstance(k, str)
                and _LUA_IDENT.fullmatch(k) is not None
                and k not in _LUA_KEYWORDS
            ):
                parts.append(f"{k}={lua_value(val)}")
            else:
                parts.append(f"[{lua_value(k)}]={lua_value(val)}")
        return "{" + ",".join(parts) + "}"
    raise TypeError(f"cannot serialize {type(v)!r}")


def _op_literal(spec: OpSpec, params: BaseModel) -> str:
    return lua_value(params.model_dump(mode="json"))


_HEADER = """-- generated by aseprite-mcp v2; do not edit
if not _G._mcp_common_loaded then
  dofile({common})
end
{categories}local _file = {file}
local _results = {{}}
local _sprite = nil
local function _resolve()
  if _sprite then return _sprite end
  _sprite = _G._mcp_get_sprite(_file)
  if not _sprite then _sprite = _G._mcp_created_sprite end
  if not _sprite then error("no sprite. Call create_sprite first.") end
  return _sprite
end
local function _record(name, ok, data)
  _results[#_results + 1] = {{op=name, ok=ok, data=data}}
  return ok
end
"""

_BOOTSTRAP_OPS = {"create_sprite", "open_sprite"}

_FOOTER = """if _saved_ok then
  _mcp_maybe_save(_sprite, _file)
end
print("\\n{marker}" .. json.encode({{ops=_results, saved=_saved_ok and true or false, error=_run_error, transaction=_tx_used}}))
"""


def compile_ops(
    parsed: list[tuple[OpSpec, BaseModel]],
    *,
    file_path: Path,
    scripts_dir: Path,
    atomic: bool,
) -> str:
    categories = sorted({spec.category for spec, _ in parsed if spec.lua})
    cat_lines = "".join(
        f"dofile({lua_string(str(scripts_dir / ('ops_' + cat + '.lua')))})\n"
        for cat in categories
    )
    header = _HEADER.format(
        common=lua_string(str(scripts_dir / "mcp_common.lua")),
        categories=cat_lines,
        file=lua_string(str(file_path)),
        marker=RESULT_MARKER,
    )

    title = lua_string(f"MCP: {len(parsed)} ops")
    first_bootstrap = bool(parsed) and parsed[0][0].name in _BOOTSTRAP_OPS

    def op_block(spec: OpSpec, params: BaseModel, index: int, *, in_body: bool) -> str:
        """One op call plus its bookkeeping.

        `index` is the op's position in the caller's batch: atomic batches abort with it so
        Python can point at the op that failed. The innermost Lua error wins over anything
        that wraps it, because that is the message naming the actual problem.
        """
        target = "_resolve()"
        after = ""
        if index == 1 and spec.name in _BOOTSTRAP_OPS:
            target = "nil"
            after = "\n  _sprite = _G._mcp_created_sprite"
        indent = "  " if in_body else ""
        block = (
            f"{indent}do\n"
            f"{indent}  local _ok, _data = pcall({spec.lua}, {target}, {_op_literal(spec, params)})\n"
            f"{indent}  _record({lua_string(spec.name)}, _ok, _data){after}\n"
            f"{indent}  if not _ok then _run_error = _run_error or tostring(_data)"
        )
        if atomic:
            block += ' _saved_ok = false; error("MCP_OP_FAILED:%d", 0)' % index
        return f"{block}\n{indent}end\n{indent}end\n\n"

    indexed = [
        (i, spec, params)
        for i, (spec, params) in enumerate(parsed, start=1)
        if spec.lua is not None
    ]

    if not atomic:
        # No transaction and no abort: every op runs, the document is saved at the end, and
        # the ops that worked survive a failure somewhere in the middle.
        body = "".join(op_block(spec, params, i, in_body=False) for i, spec, params in indexed)
        runner = f"""local _saved_ok = true
local _run_error = nil
local _tx_used = false
local _body = function()
{body}end
_body()
"""
    else:
        head = indexed[0] if first_bootstrap else None
        rest = indexed[1:] if first_bootstrap else indexed
        body = "".join(op_block(spec, params, i, in_body=True) for i, spec, params in rest)
        if head is not None:
            # create_sprite/open_sprite run first and outside the transaction: app.transaction
            # raises when no document is open, so the probe can only happen once one exists.
            prepare = (
                "local _ready_ok, _ready_err = pcall(function()\n"
                + op_block(head[1], head[2], head[0], in_body=False)
                + "end)\n"
            )
        else:
            prepare = "local _ready_ok, _ready_err = pcall(_resolve)\n"
        runner = f"""local _saved_ok = true
local _run_error = nil
local _tx_used = false
local _title = {title}
local _body = function()
{body}end
{prepare}_tx_used = (_ready_ok and pcall(app.transaction, _title, function() end)) or false
if _ready_ok then
  if _tx_used then
    local _ok, _err = pcall(app.transaction, _title, _body)
    if not _ok then _saved_ok = false; _run_error = _run_error or tostring(_err) end
  else
    local _ok, _err = pcall(_body)
    if not _ok then _saved_ok = false; _run_error = _run_error or tostring(_err) end
  end
else
  _saved_ok = false
  _run_error = _run_error or tostring(_ready_err)
end
"""

    return header + runner + _FOOTER.format(marker=RESULT_MARKER)


def parse_result_stdout(stdout: str) -> dict:
    idx = stdout.rfind(RESULT_MARKER)
    if idx == -1:
        raise ValueError(f"no {RESULT_MARKER} marker in output: {stdout!r}")
    return json.loads(stdout[idx + len(RESULT_MARKER):])